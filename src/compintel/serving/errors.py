"""RFC 9457 Problem Details error contracts and exception handlers (Phase 9, Task T9.02).

Adheres strictly to:
- architecture.md Section 11: Errors use RFC 9457 problem details with stable codes and request id.
- Rule R-ER-04: API errors use RFC 9457 problem details with stable codes and request id.
  422 for validation, 429 with Retry-After, 5xx without stack traces or internal paths.
  Abstention is HTTP 200 with status: 'abstained'.
- Rule R-ER-02: Expected outcomes return result types, not exceptions.
- Rule R-CD-03: Architectural boundary; serving never imports ingestion/quality/eval.
"""

from __future__ import annotations

from datetime import UTC, datetime
from typing import Any
from uuid import uuid4

from fastapi import FastAPI, Request, status
from fastapi.exceptions import RequestValidationError
from fastapi.responses import JSONResponse
from pydantic import BaseModel, ConfigDict, Field
from starlette.exceptions import HTTPException as StarletteHTTPException

from compintel.errors import CompIntelError, ModelArtifactError, ValidationError
from compintel.logging import get_logger

logger = get_logger(__name__)

PROBLEM_MEDIA_TYPE = "application/problem+json"


class ProblemDetails(BaseModel):
    """RFC 9457 Problem Details for HTTP APIs with CompIntel extensions."""

    model_config = ConfigDict(extra="ignore", frozen=True)

    type: str = Field(
        default="about:blank",
        description="URI reference that identifies the problem type.",
    )
    title: str = Field(
        ...,
        description="Short, human-readable summary of the problem type.",
    )
    status: int = Field(
        ...,
        description="HTTP status code generated by origin server for this occurrence.",
    )
    detail: str = Field(
        ...,
        description="Human-readable explanation specific to this occurrence of the problem.",
    )
    instance: str = Field(
        ...,
        description="URI reference that identifies the specific occurrence of the problem.",
    )
    code: str = Field(
        ...,
        description="Stable, machine-readable application error code (Rule R-ER-04).",
    )
    request_id: str = Field(
        ...,
        description="Correlation request identifier for tracing.",
    )
    errors: list[dict[str, Any]] | None = Field(
        default=None,
        description="Optional structured validation error list.",
    )
    timestamp_utc: str = Field(
        default_factory=lambda: datetime.now(UTC).isoformat(),
        description="ISO-8601 UTC timestamp of error occurrence.",
    )


def get_request_id(request: Request) -> str:
    """Safely extract correlation request ID from request state or fallback to new UUID."""
    if hasattr(request, "state") and hasattr(request.state, "request_id"):
        return str(request.state.request_id)
    return str(uuid4())


def create_problem_response(
    status_code: int,
    title: str,
    detail: str,
    code: str,
    request: Request,
    problem_type: str = "about:blank",
    errors: list[dict[str, Any]] | None = None,
    headers: dict[str, str] | None = None,
) -> JSONResponse:
    """Construct standard RFC 9457 Problem Details JSONResponse."""
    req_id = get_request_id(request)
    instance_uri = request.url.path if request.url else "/unknown"

    problem = ProblemDetails(
        type=problem_type,
        title=title,
        status=status_code,
        detail=detail,
        instance=instance_uri,
        code=code,
        request_id=req_id,
        errors=errors,
    )

    response_headers = dict(headers or {})
    response_headers["X-Request-ID"] = req_id

    return JSONResponse(
        status_code=status_code,
        content=problem.model_dump(),
        media_type=PROBLEM_MEDIA_TYPE,
        headers=response_headers,
    )


async def http_exception_handler(request: Request, exc: StarletteHTTPException) -> JSONResponse:
    """Handler for Starlette / FastAPI HTTPExceptions."""
    code_map = {
        status.HTTP_400_BAD_REQUEST: "BAD_REQUEST",
        status.HTTP_401_UNAUTHORIZED: "UNAUTHORIZED",
        status.HTTP_403_FORBIDDEN: "FORBIDDEN",
        status.HTTP_404_NOT_FOUND: "RESOURCE_NOT_FOUND",
        status.HTTP_405_METHOD_NOT_ALLOWED: "METHOD_NOT_ALLOWED",
        status.HTTP_429_TOO_MANY_REQUESTS: "RATE_LIMIT_EXCEEDED",
    }
    code = code_map.get(exc.status_code, f"HTTP_{exc.status_code}")
    title = exc.detail if isinstance(exc.detail, str) else "HTTP Error"

    return create_problem_response(
        status_code=exc.status_code,
        title=title,
        detail=str(exc.detail),
        code=code,
        request=request,
        problem_type=f"urn:compintel:problem:{code.lower()}",
        headers=dict(exc.headers) if exc.headers else None,
    )


async def request_validation_exception_handler(
    request: Request,
    exc: RequestValidationError,
) -> JSONResponse:
    """Handler for FastAPI / Pydantic schema validation errors (HTTP 422)."""
    clean_errors: list[dict[str, Any]] = []
    for err in exc.errors():
        loc_str = " -> ".join(str(loc_item) for loc_item in err.get("loc", []))
        clean_errors.append(
            {
                "location": loc_str,
                "message": err.get("msg", "Invalid value"),
                "type": err.get("type", "value_error"),
            }
        )

    return create_problem_response(
        status_code=status.HTTP_422_UNPROCESSABLE_CONTENT,
        title="Unprocessable Entity",
        detail="The request payload failed structural validation.",
        code="VALIDATION_ERROR",
        request=request,
        problem_type="urn:compintel:problem:validation-error",
        errors=clean_errors,
    )


async def app_validation_exception_handler(
    request: Request,
    exc: ValidationError,
) -> JSONResponse:
    """Handler for domain-level ValidationError (HTTP 422)."""
    code = exc.code or "VALIDATION_ERROR"
    return create_problem_response(
        status_code=status.HTTP_422_UNPROCESSABLE_CONTENT,
        title="Unprocessable Entity",
        detail=str(exc),
        code=code,
        request=request,
        problem_type="urn:compintel:problem:validation-error",
    )


async def model_artifact_exception_handler(
    request: Request,
    exc: ModelArtifactError,
) -> JSONResponse:
    """Handler for ModelArtifactError (HTTP 503 Service Unavailable)."""
    code = exc.code or "MODEL_UNAVAILABLE"
    return create_problem_response(
        status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
        title="Service Unavailable",
        detail=str(exc),
        code=code,
        request=request,
        problem_type="urn:compintel:problem:model-unavailable",
    )


async def compintel_error_handler(
    request: Request,
    exc: CompIntelError,
) -> JSONResponse:
    """Handler for uncaught domain errors in CompIntelError hierarchy."""
    code = exc.code or "APPLICATION_ERROR"
    return create_problem_response(
        status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
        title="Application Error",
        detail=str(exc),
        code=code,
        request=request,
        problem_type="urn:compintel:problem:application-error",
    )


async def unhandled_exception_handler(
    request: Request,
    exc: Exception,
) -> JSONResponse:
    """Catch-all handler for unhandled server exceptions (HTTP 500).

    Masks stack traces and internal filepaths per Rule R-ER-04 while logging internally.
    """
    req_id = get_request_id(request)
    logger.error(
        "unhandled_server_exception",
        request_id=req_id,
        path=request.url.path if request.url else "/unknown",
        method=request.method,
        exc_type=type(exc).__name__,
        exc_message=str(exc),
    )

    return create_problem_response(
        status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
        title="Internal Server Error",
        detail="An internal server error occurred while processing the request.",
        code="INTERNAL_SERVER_ERROR",
        request=request,
        problem_type="urn:compintel:problem:internal-error",
    )


def setup_exception_handlers(app: FastAPI) -> None:
    """Register all RFC 9457 exception handlers on the FastAPI application."""
    app.add_exception_handler(StarletteHTTPException, http_exception_handler)  # type: ignore[arg-type]
    app.add_exception_handler(
        RequestValidationError,
        request_validation_exception_handler,  # type: ignore[arg-type]
    )
    app.add_exception_handler(ValidationError, app_validation_exception_handler)  # type: ignore[arg-type]
    app.add_exception_handler(
        ModelArtifactError,
        model_artifact_exception_handler,  # type: ignore[arg-type]
    )
    app.add_exception_handler(CompIntelError, compintel_error_handler)  # type: ignore[arg-type]
    app.add_exception_handler(Exception, unhandled_exception_handler)
