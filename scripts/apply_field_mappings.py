def apply_mappings() -> None:
    yaml_files = sorted(sources_dir.glob("*.yaml"))
    print(f"Applying canonical field mappings across {len(yaml_files)} source files...")

    updated_count = 0
    for yf in yaml_files:
        with open(yf, encoding="utf-8") as f:
            data = yaml.safe_load(f)

        source_id = data.get("source_id", yf.stem)
        if source_id not in FIELD_MAPPINGS:
            print(f"Warning: No field mappings defined for {source_id} ({yf.name})")
            continue

        data["canonical_field_mappings"] = FIELD_MAPPINGS[source_id]

        with open(yf, "w", encoding="utf-8") as f:
            yaml.safe_dump(data, f, sort_keys=False, allow_unicode=True)

        updated_count += 1
        print(f"  [OK] Updated {source_id} with {len(FIELD_MAPPINGS[source_id])} mapped fields.")

    print(f"\nDone! Successfully updated {updated_count} source configs in {sources_dir}.")


if __name__ == "__main__":
    apply_mappings()
