#!/usr/bin/env python3
"""WCAG 2.2 Contrast Ratio Verification and Token Generator (T9.07, design.md section 5 & 13).

Computes exact relative luminance and contrast ratios for all colour token pairs
defined in `apps/web/src/styles/tokens.json` for both Light and Dark themes.
Enforces:
- Normal text requires at least 4.5:1.
- Controls and graphics require at least 3.0:1.
- Generates/validates `apps/web/src/styles/tokens.css` from the token single source of truth.

Usage:
    uv run python scripts/check_contrast.py [--generate-css] [--tokens-path <path>]
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any, NamedTuple


def srgb_channel_to_linear(val: float) -> float:
    """Convert an sRGB channel value [0, 1] to linear luminance."""
    return val / 12.92 if val <= 0.04045 else ((val + 0.055) / 1.055) ** 2.4


def hex_to_relative_luminance(hex_str: str) -> float:
    """Calculate WCAG 2.2 relative luminance for a hex colour code."""
    clean = hex_str.strip().lstrip("#")
    if len(clean) == 3:
        clean = "".join([c * 2 for c in clean])
    if len(clean) != 6:
        raise ValueError(f"Invalid hex color code: '{hex_str}'")

    r = int(clean[0:2], 16) / 255.0
    g = int(clean[2:4], 16) / 255.0
    b = int(clean[4:6], 16) / 255.0

    return (
        0.2126 * srgb_channel_to_linear(r)
        + 0.7152 * srgb_channel_to_linear(g)
        + 0.0722 * srgb_channel_to_linear(b)
    )


def contrast_ratio(hex1: str, hex2: str) -> float:
    """Calculate WCAG contrast ratio between two hex colours."""
    l1 = hex_to_relative_luminance(hex1)
    l2 = hex_to_relative_luminance(hex2)
    lighter = max(l1, l2)
    darker = min(l1, l2)
    return (lighter + 0.05) / (darker + 0.05)


class ContrastCheckResult(NamedTuple):
    name: str
    kind: str
    min_ratio: float
    light_ratio: float
    expected_light: float
    light_pass: bool
    dark_ratio: float
    expected_dark: float
    dark_pass: bool


def verify_token_contrasts(tokens_data: dict[str, Any]) -> list[ContrastCheckResult]:
    """Verify all token pairs defined in the tokens data."""
    light_tokens = tokens_data["tokens"]["light"]
    dark_tokens = tokens_data["tokens"]["dark"]
    pairs = tokens_data["verified_pairs"]

    results: list[ContrastCheckResult] = []

    for pair in pairs:
        name = pair["name"]
        fg_key = pair["fg"]
        bg_key = pair["bg"]
        min_ratio = float(pair["min_ratio"])
        expected_light = float(pair["expected_light"])
        expected_dark = float(pair["expected_dark"])
        kind = pair.get("kind", "text")

        fg_light = light_tokens[fg_key]
        bg_light = light_tokens[bg_key]
        fg_dark = dark_tokens[fg_key]
        bg_dark = dark_tokens[bg_key]

        light_ratio = round(contrast_ratio(fg_light, bg_light), 2)
        dark_ratio = round(contrast_ratio(fg_dark, bg_dark), 2)

        # Passes if ratio meets the minimum required by WCAG and aligns with design.md (tolerance 0.05)
        light_pass = light_ratio >= min_ratio and abs(light_ratio - expected_light) <= 0.05
        dark_pass = dark_ratio >= min_ratio and abs(dark_ratio - expected_dark) <= 0.05

        results.append(
            ContrastCheckResult(
                name=name,
                kind=kind,
                min_ratio=min_ratio,
                light_ratio=light_ratio,
                expected_light=expected_light,
                light_pass=light_pass,
                dark_ratio=dark_ratio,
                expected_dark=expected_dark,
                dark_pass=dark_pass,
            )
        )

    return results


def generate_tokens_css(tokens_data: dict[str, Any]) -> str:
    """Generate tokens.css containing light, dark, and shadcn variables per design.md section 13."""
    light = tokens_data["tokens"]["light"]
    dark = tokens_data["tokens"]["dark"]

    css_lines = [
        "/* ==========================================================================",
        "   ArthaIQ Design Tokens — Single Source of Truth",
        "   Generated by scripts/check_contrast.py from tokens.json",
        "   Per design.md sections 5 & 13. DO NOT EDIT DIRECTLY.",
        "   ========================================================================== */",
        "",
        ":root {",
    ]

    for key, val in light.items():
        css_lines.append(f"  --{key}: {val};")

    css_lines.extend(
        [
            "",
            "  /* shadcn/ui semantic variable mappings */",
            "  --background: var(--paper);",
            "  --foreground: var(--ink);",
            "  --card: var(--sheet);",
            "  --card-foreground: var(--ink);",
            "  --popover: var(--sheet);",
            "  --popover-foreground: var(--ink);",
            "  --primary: var(--span);",
            "  --primary-foreground: var(--on-span);",
            "  --secondary: var(--sunken);",
            "  --secondary-foreground: var(--ink);",
            "  --muted: var(--sunken);",
            "  --muted-foreground: var(--ink-3);",
            "  --accent: var(--span-wash);",
            "  --accent-foreground: var(--span-strong);",
            "  --destructive: var(--alert);",
            "  --destructive-foreground: var(--sheet);",
            "  --border: var(--rule);",
            "  --input: var(--rule-strong);",
            "  --ring: var(--focus);",
            "  --radius: var(--radius-control);",
            "}",
            "",
            ':root[data-theme="dark"] {',
        ]
    )

    for key, val in dark.items():
        css_lines.append(f"  --{key}: {val};")

    css_lines.extend(
        [
            "}",
            "",
            "/* System dark preference fallback */",
            "@media (prefers-color-scheme: dark) {",
            '  :root:not([data-theme="light"]) {',
        ]
    )

    for key, val in dark.items():
        css_lines.append(f"    --{key}: {val};")

    css_lines.extend(
        [
            "  }",
            "}",
            "",
            "/* Base typographical and figure utilities */",
            "body {",
            "  font-family: var(--font-sans);",
            "  color: var(--ink);",
            "  background-color: var(--paper);",
            "}",
            "",
            ".figure {",
            "  font-family: var(--font-serif);",
            "  font-variant-numeric: tabular-nums lining-nums;",
            "}",
            "",
        ]
    )

    return "\n".join(css_lines)


def main(args: list[str] | None = None) -> int:
    """CLI runner for contrast verification and token generation."""
    parser = argparse.ArgumentParser(description="Check token contrast ratios and generate CSS.")
    parser.add_argument(
        "--tokens-path",
        type=Path,
        default=Path("apps/web/src/styles/tokens.json"),
        help="Path to tokens.json file.",
    )
    parser.add_argument(
        "--generate-css",
        action="store_true",
        default=True,
        help="Generate apps/web/src/styles/tokens.css from tokens.json.",
    )
    parsed = parser.parse_args(args)

    if not parsed.tokens_path.exists():
        print(f"ERROR: Tokens file not found at {parsed.tokens_path}", file=sys.stderr)
        return 1

    with open(parsed.tokens_path, encoding="utf-8") as f:
        tokens_data = json.load(f)

    print("=" * 88)
    print("ArthaIQ WCAG 2.2 Contrast Verification (T9.07, design.md section 5)")
    print("=" * 88)

    results = verify_token_contrasts(tokens_data)

    print(f"{'Token Pair':<40} {'Kind':<8} {'Min':<6} {'Light':<12} {'Dark':<12} {'Status':<6}")
    print("-" * 88)

    all_passed = True
    for r in results:
        light_str = f"{r.light_ratio:.2f}:1"
        dark_str = f"{r.dark_ratio:.2f}:1"
        status = "PASS" if r.light_pass and r.dark_pass else "FAIL"

        if not (r.light_pass and r.dark_pass):
            all_passed = False

        print(
            f"{r.name:<40} {r.kind:<8} {r.min_ratio:<6.1f} {light_str:<12} {dark_str:<12} {status:<6}"
        )

    print("=" * 88)

    if parsed.generate_css:
        css_content = generate_tokens_css(tokens_data)
        out_css = parsed.tokens_path.parent / "tokens.css"
        out_css.write_text(css_content, encoding="utf-8")
        print(f"Generated tokens.css at {out_css}")

    if all_passed:
        print("SUCCESS: All 15 token pairs strictly satisfy WCAG 2.2 AA contrast requirements.")
        return 0
    else:
        print("FAILURE: Contrast verification failed for one or more token pairs.", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
